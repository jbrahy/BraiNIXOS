/// Encodes one property record: 32-byte NUL-padded name, little-endian length
/// word, value, zero padding to a multiple of 4.
pub fn property(name: &str, value: &[u8]) -> Vec<u8> {
    let mut out = Vec::new();
    let name_bytes = name.as_bytes();
    assert!(name_bytes.len() < 32, "test property name too long");
    out.extend_from_slice(name_bytes);
    out.resize(32, 0);
    out.extend_from_slice(&(value.len() as u32).to_le_bytes());
    out.extend_from_slice(value);
    while out.len() % 4 != 0 {
        out.push(0);
    }
    out
}

/// Encodes a node: 8-byte header, then properties, then children.
pub fn node(properties: &[Vec<u8>], children: &[Vec<u8>]) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(&(properties.len() as u32).to_le_bytes());
    out.extend_from_slice(&(children.len() as u32).to_le_bytes());
    for property in properties {
        out.extend_from_slice(property);
    }
    for child in children {
        out.extend_from_slice(child);
    }
    out
}

/// A NUL-terminated string value.
pub fn cstr(text: &str) -> Vec<u8> {
    let mut out = text.as_bytes().to_vec();
    out.push(0);
    out
}

/// A little-endian u32 value.
pub fn u32_value(value: u32) -> Vec<u8> {
    value.to_le_bytes().to_vec()
}

/// A 64-bit quantity as two cells, least-significant cell first.
pub fn two_cells(value: u64) -> Vec<u8> {
    let mut out = Vec::new();
    out.extend_from_slice(&((value & 0xffff_ffff) as u32).to_le_bytes());
    out.extend_from_slice(&((value >> 32) as u32).to_le_bytes());
    out
}

/// Overwrites a little-endian u32 at `offset` in a copy of `blob`.
pub fn patched_u32(blob: &[u8], offset: usize, value: u32) -> Vec<u8> {
    let mut out = blob.to_vec();
    out[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
    out
}

/// Overwrites a single byte at `offset` in a copy of `blob`.
pub fn patched_byte(blob: &[u8], offset: usize, value: u8) -> Vec<u8> {
    let mut out = blob.to_vec();
    out[offset] = value;
    out
}

/// Buffer-relative offset of a borrowed sub-slice. Used to pin the golden
/// fixture's record offsets without exposing internals.
pub fn offset_of(blob: &[u8], part: &[u8]) -> usize {
    (part.as_ptr() as usize) - (blob.as_ptr() as usize)
}
